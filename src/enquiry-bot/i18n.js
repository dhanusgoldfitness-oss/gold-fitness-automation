export function t(lang, key, params = {}) {
  const raw = (S[lang] && S[lang][key]) ?? S.en[key];
  if (raw === undefined) throw new Error(`missing i18n key: ${key}`);
  return raw.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ""));
}

export function mainMenuText(lang) {
  const titles = MENU_TITLES[lang] || MENU_TITLES.en;
  const lines = titles.map((title, i) => `${i + 1}. ${title}`).join("\n");
  return `${t(lang, "menuIntro")}\n\n${lines}\n\n${t(lang, "menuFooter")}`;
}

